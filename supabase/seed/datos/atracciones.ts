function casco(
  municipioId: string,
  nombre: string,
  lat: number,
  lon: number,
): AtraccionSeed {
  return {
    id: `${municipioId}-casco`,
    municipio_id: municipioId,
    nombre: `Casco urbano de ${nombre}`,
    categoria: 'casco_urbano',
    lat,
    lon,
    es_casco_urbano: true,
    costo_entrada_cop: 0,
    costo_aproximado: false,
    duracion_min: 60,
    minutos_desde_casco: 0,
    transporte_local_cop: 0,
    dias_cerrado: [],
    al_aire_libre: true,
    estilos: ['cultura_cafetera', 'descanso'],
    requiere_guia: false,
    estado_acceso: 'abierta',
    radio_checkin_m: 1500,
    descripcion:
      'Centro del municipio: plaza principal, iglesia y comercio. Punto de referencia para check-in y traslados.',
    fecha_actualizacion: REV,
    fuente: 'DANE DIVIPOLA (coordenadas de la cabecera), ver FUENTES.md',
  };
}

